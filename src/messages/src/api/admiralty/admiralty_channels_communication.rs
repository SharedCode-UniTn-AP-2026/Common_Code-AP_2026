//! Channel creation and configuration interfaces.

use std::collections::HashMap;

use crossbeam_channel::{Receiver, Sender};

use shared::ShipId;

use crate::channels::{
    AdmiraltyToCartographerChannel,
    AdmiraltyToShipChannel,
    CartographerToAdmiraltyChannel,
    ShipToAdmiraltyChannel,
};

use crate::messages::{
    AdmiraltyToCartographer,
    AdmiraltyToShip,
    CartographerToAdmiralty,
    ShipToAdmiralty,
};

/// Result of a communication operation.
#[derive(Debug)]
pub enum CommsOutcome<T> {
    /// Operation completed successfully.
    Success(T),

    /// Destination channel is full.
    Full,

    /// No message was received before the deadline.
    TimeOut,

    /// The endpoint does not exist or is disconnected.
    NonExistent,
}

/// Struct that represents the channels generated by the Admiralty that have to be passed to the respective entities, either the Cartographer or a Ship
pub struct GeneratedChannels {
    /// Channels that have to passed to the respective Ships.
    ///
    /// Ships will use these channels to communicate with the Admiralty.
    pub ships: HashMap<ShipId, ShipToAdmiraltyChannel>,
    /// Channels that have to be passed to the Cartographer.
    ///
    /// Cartographer will use these channels to communicate with the Admiralty.
    pub cartographer: CartographerToAdmiraltyChannel,
}

/// Trait that defines functions for creating channels
pub trait ChannelsCreation {
    /// Generates the tuple (Sender, Receiver) for the channel : **Admiralty -> Ship**
    fn generate_channels_admiralty_to_ship(
        channel_capacity: usize,
    ) -> (Sender<AdmiraltyToShip>, Receiver<AdmiraltyToShip>);

    /// Generates the tuple (Sender, Receiver) for the channel : **Ship -> Admiralty**
    fn generate_channels_ship_to_admiralty(
        channel_capacity: usize,
    ) -> (Sender<ShipToAdmiralty>, Receiver<ShipToAdmiralty>);

    /// Generates the tuple (Sender, Receiver) for the channel : **Admiralty -> Cartographer**
    fn generate_channels_admiralty_to_cartographer(
        channel_capacity: usize,
    ) -> (Sender<AdmiraltyToCartographer>, Receiver<AdmiraltyToCartographer>);

    /// Generates the tuple (Sender, Receiver) for the channel : **Cartographer -> Admiralty**
    fn generate_channels_cartographer_to_admiralty(
        channel_capacity: usize,
    ) -> (Sender<CartographerToAdmiralty>, Receiver<CartographerToAdmiralty>);

    /// Generates the channels for each ship.
    ///
    /// # Returns
    /// Returns two hashmaps in a tuple :
    /// 1. Contains the channels used by the Admiralty to talk to each ship.
    /// 2. Contains the channels used by each ship to talk to the Admiralty.
    fn generate_ship_channels<T: Iterator<Item = ShipId>>(
        ship_ids: T,
        channel_capacity: usize,
    ) -> (
        HashMap<ShipId, ShipToAdmiraltyChannel>,
        HashMap<ShipId, AdmiraltyToShipChannel>,
    );

    /// Generates the channels for the cartographer.
    fn generate_cartographer_channels(
        channel_capacity: usize
    ) -> (
        CartographerToAdmiraltyChannel,
        AdmiraltyToCartographerChannel
    );
}

/// Trait that defines functions for managing settings channels
pub trait ChannelsModifySettings {
    /// Updates the response deadline for the channels.
    pub fn update_deadline(&mut self, new_deadline: u64);
}
